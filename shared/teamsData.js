export function getClubById(clubId) {
  return CLUBS.find((c) => c.id === clubId) || CLUBS[0];
}

export function getClubsByRegion(regionId) {
  return CLUBS.filter((c) => c.region === regionId);
}

export function getUnlockablePlayerById(playerId) {
  return UNLOCKABLE_PLAYERS.find((p) => p.id === playerId) || null;
}

export function buildEffectiveRoster(clubId, customDraftIds = []) {
  const club = getClubById(clubId);
  const roster = club.roster.map((p) => ({ ...p }));
  if (!Array.isArray(customDraftIds) || customDraftIds.length === 0) {
    return roster;
  }
  const replaceOrder = [4, 3, 2, 1];
  customDraftIds.slice(0, 4).forEach((unlockId, idx) => {
    const star = getUnlockablePlayerById(unlockId);
    if (star) {
      const targetSlot = replaceOrder[idx];
      roster[targetSlot] = {
        ...star,
        role: roster[targetSlot].role,
      };
    }
  });
  return roster;
}
